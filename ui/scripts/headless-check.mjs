// Headless browser check of the built demo (needs `npm i -D playwright && npx playwright install chromium`).
// Usage: npx serve docs -l 4173 & node ui/scripts/headless-check.mjs http://localhost:4173/
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://localhost:4173/';
const width = Number(process.argv[3] ?? 1280);
const shot = process.argv[4] ?? '/tmp/pw/shot.png';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(url);
await page.waitForSelector('text=Record meeting #12', { timeout: 30000 });
const t = (s) => page.locator(s).first();
console.log('loaded; status:', await t('.status').innerText());
await t('button:has-text("Record meeting #12")').click();
await page.waitForSelector('text=Meeting #12 recorded', { timeout: 30000 });
console.log('recorded #12');
console.log('passbook:', (await t('.book').innerText()).replace(/\n/g, ' '));
await t('button:has-text("Grant ends")').click();
await page.waitForTimeout(300);
await t('button:has-text("Call sunset()")').click().catch(()=>{});
await page.waitForTimeout(300);
console.log('early sunset log:', (await t('.log li').innerText()).slice(0,160));
await t('.story button:has-text("Skip")').click();
await page.waitForTimeout(300);
await t('button:has-text("Call sunset()")').click();
await page.waitForTimeout(300);
console.log('status after sunset:', await t('.status').innerText());
await t('button:has-text("Record meeting #13")').click();
await page.waitForSelector('text=Meeting #13 recorded', { timeout: 30000 });
console.log('recorded #13 after sunset:', await t('.screen .ok').innerText());
await t('button:has-text("Try to open slot 0")').click();
console.log('explorer:', await t('.phone.public .err').innerText().catch(()=> 'n/a (hidden on mobile)'));
await t('button:has-text("Prove")').click();
await page.waitForTimeout(300);
console.log('story:', (await t('.story').innerText()).replace(/\n/g,' | '));
await page.screenshot({ path: shot, fullPage: true });
console.log('ERRORS:', errors.length ? errors : 'none');
await browser.close();
